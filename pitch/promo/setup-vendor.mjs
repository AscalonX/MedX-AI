#!/usr/bin/env node
// Copies the render-time vendor files into promo/ so the composition never
// touches node_modules or the network at render time:
//   promo/vendor/  <- gsap dist *.min.js (core + plugins)
//   promo/fonts/   <- @fontsource woff2 (Plus Jakarta Sans 500-800, Noto Sans Thai 500-700)
//                     + fonts.css (@font-face, font-display: block) + OFL licence texts
// Non-destructive: an existing file is never overwritten unless --force is given.
// Usage: node pitch/promo/setup-vendor.mjs [--force]
// Packages come from pitch/promo/node_modules (npm --prefix pitch/promo install), or from
// <MEDX_TOOLS>/node_modules when that env var is set.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const PROMO = path.dirname(fileURLToPath(import.meta.url));
const NM = path.join(process.env.MEDX_TOOLS || PROMO, 'node_modules');
const FORCE = process.argv.includes('--force');
let copied = 0, skipped = 0;

function put(dest, writer) {
  if (fs.existsSync(dest) && !FORCE) { skipped++; return; }
  fs.mkdirSync(path.dirname(dest), { recursive: true });
  writer(dest);
  copied++;
}
const copy = (src, dest) => {
  if (!fs.existsSync(src)) throw new Error(`missing source ${src} (run: npm --prefix pitch/promo install)`);
  put(dest, (d) => fs.copyFileSync(src, d));
};

// 1. gsap
const gsapDist = path.join(NM, 'gsap', 'dist');
for (const f of fs.readdirSync(gsapDist).filter((f) => f.endsWith('.min.js'))) {
  copy(path.join(gsapDist, f), path.join(PROMO, 'vendor', f));
}

// 2. fonts
const FAMILIES = [
  { pkg: 'plus-jakarta-sans', family: 'Plus Jakarta Sans', subsets: ['latin', 'latin-ext'], weights: [500, 600, 700, 800] },
  { pkg: 'noto-sans-thai', family: 'Noto Sans Thai', subsets: ['thai', 'latin'], weights: [500, 600, 700] },
];
let css = '/* Generated by setup-vendor.mjs from @fontsource (OFL-1.1). Local files only. */\n';
for (const fam of FAMILIES) {
  const root = path.join(NM, '@fontsource', fam.pkg);
  for (const w of fam.weights) {
    // Reuse fontsource's own unicode-range for each subset.
    const src = fs.readFileSync(path.join(root, `${w}.css`), 'utf8');
    for (const sub of fam.subsets) {
      const file = `${fam.pkg}-${sub}-${w}-normal.woff2`;
      copy(path.join(root, 'files', file), path.join(PROMO, 'fonts', file));
      const block = src.split('@font-face').find((b) => b.includes(`/${file})`));
      const range = block && /unicode-range:\s*([^;]+);/.exec(block);
      css += `@font-face {\n  font-family: '${fam.family}';\n  font-style: normal;\n  font-display: block;\n  font-weight: ${w};\n  src: url(./${file}) format('woff2');\n${range ? `  unicode-range: ${range[1]};\n` : ''}}\n`;
    }
  }
  const lic = path.join(root, 'LICENSE');
  if (fs.existsSync(lic)) copy(lic, path.join(PROMO, 'fonts', `LICENSE-${fam.pkg}.txt`));
}
put(path.join(PROMO, 'fonts', 'fonts.css'), (d) => fs.writeFileSync(d, css));

console.log(`[setup-vendor] copied ${copied}, kept ${skipped} existing${FORCE ? ' (forced)' : ''}`);
console.log(`[setup-vendor] vendor: ${path.join(PROMO, 'vendor')}  fonts: ${path.join(PROMO, 'fonts')}`);
